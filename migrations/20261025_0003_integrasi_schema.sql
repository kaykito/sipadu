-- Skema modul Integrasi SIM RS – BLUD:
--   REKENING_RBA, LAYANAN_RS          -> modul mappingRba
--   KAS_SIMRS, KAS_SIMRS_DETAIL       -> modul kasSimrs (bukti TBP/STS dari SIM RS + rincian rekening)
--   REKAP_PENERIMAAN                  -> modul rekapPenerimaan (KAS_SIMRS.keyREKAP menunjuk ke rekap)
--   BERITA_ACARA                      -> modul beritaAcara
--   LOG_API                           -> modul logApi
--   PENGATURAN_INTEGRASI (satu baris) -> modul pengaturanIntegrasi

IF OBJECT_ID(N'dbo.REKENING_RBA', N'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[REKENING_RBA] (
    [keyREK] BIGINT IDENTITY(1,1) NOT NULL,
    [kdREK] NVARCHAR(30) NOT NULL,
    [uraian] NVARCHAR(200) NOT NULL,
    [levelREK] INT DEFAULT ((6)) NOT NULL,
    [layananTerhubung] NVARCHAR(255) NULL,
    CONSTRAINT [PK_REKENING_RBA] PRIMARY KEY CLUSTERED ([keyREK] ASC),
    CONSTRAINT [UQ_REKENING_RBA_kdREK] UNIQUE NONCLUSTERED ([kdREK] ASC)
    );
END
GO

IF OBJECT_ID(N'dbo.LAYANAN_RS', N'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[LAYANAN_RS] (
    [keyLAYANAN] BIGINT IDENTITY(1,1) NOT NULL,
    [kdLAYANAN] NVARCHAR(20) NOT NULL,
    [uraian] NVARCHAR(200) NOT NULL,
    [keyREK] BIGINT NULL,
    CONSTRAINT [PK_LAYANAN_RS] PRIMARY KEY CLUSTERED ([keyLAYANAN] ASC),
    CONSTRAINT [UQ_LAYANAN_RS_kdLAYANAN] UNIQUE NONCLUSTERED ([kdLAYANAN] ASC),
    CONSTRAINT [FK_LAYANAN_RS_REKENING_RBA] FOREIGN KEY ([keyREK]) REFERENCES [dbo].[REKENING_RBA] ([keyREK])
    );
END
GO

IF OBJECT_ID(N'dbo.REKAP_PENERIMAAN', N'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[REKAP_PENERIMAAN] (
    [keyREKAP] BIGINT IDENTITY(1,1) NOT NULL,
    [noREKAP] NVARCHAR(20) NOT NULL,
    [tglREKAP] DATE NOT NULL,
    [jenis] VARCHAR(3) NOT NULL,
    [uraian] NVARCHAR(255) NOT NULL,
    [tglSetor] DATE NOT NULL,
    [bank] NVARCHAR(100) NULL,
    [noRek] NVARCHAR(50) NULL,
    [nmRek] NVARCHAR(100) NULL,
    [statusApi] VARCHAR(10) DEFAULT ('pending') NOT NULL,
    [createdBy] NVARCHAR(100) NULL,
    [createdAt] DATETIME DEFAULT (getdate()) NOT NULL,
    CONSTRAINT [PK_REKAP_PENERIMAAN] PRIMARY KEY CLUSTERED ([keyREKAP] ASC),
    CONSTRAINT [UQ_REKAP_PENERIMAAN_noREKAP] UNIQUE NONCLUSTERED ([noREKAP] ASC),
    CONSTRAINT [CK_REKAP_PENERIMAAN_jenis] CHECK ([jenis] IN ('TBP', 'STS')),
    CONSTRAINT [CK_REKAP_PENERIMAAN_statusApi] CHECK ([statusApi] IN ('pending', 'success', 'failed'))
    );
END
GO

IF OBJECT_ID(N'dbo.KAS_SIMRS', N'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[KAS_SIMRS] (
    [keyKAS] BIGINT IDENTITY(1,1) NOT NULL,
    [noBukti] NVARCHAR(30) NOT NULL,
    [tglKAS] DATETIME NOT NULL,
    [penyetor] NVARCHAR(150) NOT NULL,
    [jenis] VARCHAR(3) NOT NULL,
    [total] DECIMAL(18,2) DEFAULT ((0)) NOT NULL,
    [bank] NVARCHAR(100) NULL,
    [noRek] NVARCHAR(50) NULL,
    [statusSync] VARCHAR(10) DEFAULT ('pending') NOT NULL,
    [keyREKAP] BIGINT NULL,
    [createdAt] DATETIME DEFAULT (getdate()) NOT NULL,
    CONSTRAINT [PK_KAS_SIMRS] PRIMARY KEY CLUSTERED ([keyKAS] ASC),
    CONSTRAINT [UQ_KAS_SIMRS_noBukti] UNIQUE NONCLUSTERED ([noBukti] ASC),
    CONSTRAINT [CK_KAS_SIMRS_jenis] CHECK ([jenis] IN ('TBP', 'STS')),
    CONSTRAINT [CK_KAS_SIMRS_statusSync] CHECK ([statusSync] IN ('pending', 'success', 'failed')),
    CONSTRAINT [FK_KAS_SIMRS_REKAP_PENERIMAAN] FOREIGN KEY ([keyREKAP]) REFERENCES [dbo].[REKAP_PENERIMAAN] ([keyREKAP]) ON DELETE SET NULL
    );
END
GO

